function fromLib(
  kind: string,
  x: number,
  y: number,
  groupId: string,
  overrides?: Partial<Omit<DrawingElement, 'id' | 'zIndex'>>
): Omit<DrawingElement, 'id' | 'zIndex'> {
  const spec = DRAWING_LIBRARY_ITEMS.find((item) => item.kind === kind)!;
  return {
    kind: spec.kind,
    name: spec.name,
    category: spec.category,
    x,
    y,
    width: overrides?.width ?? spec.defaultWidth,
    height: overrides?.height ?? spec.defaultHeight,
    rotation: overrides?.rotation ?? 0,
    fill: overrides?.fill ?? spec.defaultFill,
    stroke: overrides?.stroke ?? spec.defaultStroke,
    strokeWidth: overrides?.strokeWidth ?? 1.8,
    strokeDash: overrides?.strokeDash ?? 'solid',
    opacity: overrides?.opacity ?? 1,
    locked: false,
    groupId,
    params: { ...spec.defaultParams, ...(overrides?.params || {}) },
  };
}

