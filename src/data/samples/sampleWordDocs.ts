export function cloneSampleWordDoc(tpl: WordDocumentRecord): WordDocumentRecord {
  const now = Date.now();
  return {
    ...tpl,
    id: generateId('doc'),
    source: 'created',
    blocks: tpl.blocks.map((b) => ({
      ...b,
      id: generateId('blk'),
      tableHeaders: b.tableHeaders ? [...b.tableHeaders] : undefined,
      tableRows: b.tableRows ? b.tableRows.map((r) => [...r]) : undefined,
    })),
    createdAt: now,
    updatedAt: now,
  };
}
